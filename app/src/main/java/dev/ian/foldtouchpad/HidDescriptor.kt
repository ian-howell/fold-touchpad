package dev.ian.foldtouchpad

/** Combined keyboard (report 1) + mouse (report 2) HID report descriptor. */
object HidDescriptor {
    const val ID_KEYBOARD: Int = 1
    const val ID_MOUSE: Int = 2

    val DESCRIPTOR: ByteArray = intArrayOf(
        // Keyboard
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01,
        0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,       // modifiers
        0x75, 0x08, 0x95, 0x01, 0x81, 0x01,       // reserved
        0x75, 0x08, 0x95, 0x06, 0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, // 6 keys
        0xC0,
        // Mouse
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01,
        0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x05, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, // x, y, wheel
        0x05, 0x0C, 0x0A, 0x38, 0x02,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06, // h-wheel
        0xC0,
        0xC0,
    ).map { it.toByte() }.toByteArray()
}
